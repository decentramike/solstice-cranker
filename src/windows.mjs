/**
 * When the workflows are allowed to do work.
 *
 * Pure functions over the schedule file (config/schedule.<network>.json) and the clock. This
 * module imports nothing outside Node, on purpose: the gate step that uses it runs before
 * `npm ci`, with no key, and has to answer in seconds.
 *
 * The crank window for quarter Q
 * ------------------------------
 *   opens   binding(Q) - 1 hour
 *   closes  when BOTH submitShares(Q) and the gate check due at Q have landed on chain
 *
 * Elapsed time never closes it. A window that is still open after 72 hours is a window whose
 * work has not landed, which is exactly when the cranker must keep trying. What 72 hours
 * changes is the cadence: every run before it, every 6th hourly run after it.
 *
 * "Due at Q" for the gate means what the cranker's own schedule means by it (schedule.mjs):
 * the gate's next target is lastCheckedQuarter + 1, and it is due once that target <= Q.
 * So the gate side is settled when lastCheckedQuarter >= Q, or the gate has taken all its steps.
 *
 * All arithmetic here is in epochs, so the devnet (whose epochs are not wall-clock) can drive
 * the same code by passing an epoch directly.
 */

export const HOUR_SECONDS = 3600;
export const EVERY_RUN_HOURS = 72;
export const THIN_EVERY_HOURS = 6;
export const OPEN_BEFORE_BINDING_HOURS = 1;
export const POST_SUBMIT_DELAY_HOURS = 24;
export const POST_SUBMIT_WINDOW_HOURS = 72;

const hours = (sched, h) => Math.round((h * HOUR_SECONDS) / sched.epochSeconds);

export const quarterStart = (g, q) => g.activationEpoch + q * g.epochsPerQuarter;
export const binding = (g, q) => quarterStart(g, q) + g.postPeriod + g.verificationWindow;
export const deadline = (g, q) => binding(g, q + 1);

export function epochToUnix(sched, epoch) {
  if (sched.genesisUnix === null || sched.genesisUnix === undefined) return null;
  return sched.genesisUnix + epoch * sched.epochSeconds;
}

export function unixToEpoch(sched, unix) {
  if (sched.genesisUnix === null || sched.genesisUnix === undefined) throw new Error('this network has no wall clock; pass an epoch');
  return Math.floor((unix - sched.genesisUnix) / sched.epochSeconds);
}

const iso = (sched, epoch) => {
  const u = epochToUnix(sched, epoch);
  return u === null ? null : new Date(u * 1000).toISOString().replace('.000Z', 'Z');
};

/**
 * The schedule file's content. `fromEpoch` is the chain head when generated; the list starts
 * at the first quarter whose submit window has not closed by then.
 */
export function buildScheduleFile({ network, geometry, genesisUnix, epochSeconds, addresses, headEpoch, count = 8, generatedAt, sources }) {
  const g = geometry;
  if (g.postPeriod + g.verificationWindow >= g.epochsPerQuarter) throw new Error('postPeriod + verificationWindow must be less than epochsPerQuarter');
  const sched = { genesisUnix, epochSeconds };
  let first = 1;
  while (deadline(g, first) <= headEpoch) first += 1;
  const quarters = [];
  for (let q = first; q < first + count; q++) {
    const b = binding(g, q);
    const opens = b - hours(sched, OPEN_BEFORE_BINDING_HOURS);
    quarters.push({
      quarter: q,
      quarterStartEpoch: quarterStart(g, q),
      bindingEpoch: b,
      bindingUtc: iso(sched, b),
      windowOpensUtc: iso(sched, opens),
      everyRunUntilUtc: iso(sched, opens + hours(sched, EVERY_RUN_HOURS)),
      postSubmitClaimFromUtc: iso(sched, b + hours(sched, POST_SUBMIT_DELAY_HOURS)),
      deadlineEpoch: deadline(g, q),
      deadlineUtc: iso(sched, deadline(g, q)),
    });
  }
  return {
    $comment: [
      'Generated by `npm run schedule`. Do not edit by hand; regenerate.',
      'The gate step of each workflow reads this file before anything else runs. Binding(Q) is when',
      'submitShares(Q) becomes callable; the deadline is binding(Q+1), after which Q is lost for good.',
    ],
    network,
    generatedAt,
    generatedAtEpoch: headEpoch,
    genesisUnix,
    epochSeconds,
    geometry: { ...g },
    addresses,
    sources,
    quarters,
  };
}

/**
 * The crank window the clock is in, before chain state is consulted.
 * Returns null before the first window opens.
 */
export function crankWindowAt(sched, epoch) {
  const g = sched.geometry;
  const open = hours(sched, OPEN_BEFORE_BINDING_HOURS);
  // Latest q with binding(q) - 1h <= epoch. binding is monotonic in q.
  let q = Math.max(0, Math.floor((epoch + open - g.activationEpoch - g.postPeriod - g.verificationWindow) / g.epochsPerQuarter));
  while (q >= 1 && binding(g, q) - open > epoch) q -= 1;
  while (binding(g, q + 1) - open <= epoch) q += 1;
  if (q < 1) return null;
  const opensEpoch = binding(g, q) - open;
  const hoursOpen = Math.floor(((epoch - opensEpoch) * sched.epochSeconds) / HOUR_SECONDS);
  const everyRun = hoursOpen < EVERY_RUN_HOURS;
  return {
    quarter: q,
    opensEpoch,
    bindingEpoch: binding(g, q),
    deadlineEpoch: deadline(g, q),
    hoursOpen,
    everyRun,
    // After 72 hours: one hour in six. Every trigger that falls in that hour runs.
    thinnedOut: !everyRun && hoursOpen % THIN_EVERY_HOURS !== 0,
  };
}

/**
 * Has quarter q's work landed? Both halves must be confirmed from chain state.
 * @param {{lastSubmittedQuarter: number, lastCheckedQuarter: number, gateComplete: boolean}} chain
 */
export function windowClosed(chain, q) {
  const submitted = chain.lastSubmittedQuarter >= q;
  const gateSettled = chain.gateComplete || chain.lastCheckedQuarter >= q;
  return { closed: submitted && gateSettled, submitted, gateSettled };
}

/**
 * The crank gate.
 *
 * @param {object} p
 * @param {object} p.sched     schedule file
 * @param {number} p.epoch     now, in epochs
 * @param {object|null} p.chain   chain state from the gate's storage probe, or null if it failed
 * @param {boolean} [p.ignoreWindow] a person pressed Run workflow and asked to bypass the gate
 */
export function decideCrank({ sched, epoch, chain, ignoreWindow = false }) {
  if (ignoreWindow) return { go: true, reason: 'run requested with ignore_window' };
  const w = crankWindowAt(sched, epoch);
  if (!w) return { go: false, reason: 'before the first crank window', window: null };
  if (w.thinnedOut) {
    return { go: false, reason: `Q${w.quarter} window open ${w.hoursOpen}h; past 72h this runs one hour in six`, window: w };
  }
  if (!chain) {
    // Cannot see the chain: fail open. A wasted run costs nothing; a skipped one can cost a quarter.
    return { go: true, reason: `inside the Q${w.quarter} window and chain state is unreadable; running`, window: w };
  }
  const c = windowClosed(chain, w.quarter);
  if (c.closed) return { go: false, reason: `Q${w.quarter} window closed on chain: submitShares(${w.quarter}) landed and the gate is settled`, window: w, closure: c };
  return {
    go: true,
    reason: `inside the Q${w.quarter} window (${w.hoursOpen}h open): ${c.submitted ? 'submitted' : 'submitShares pending'}, ${c.gateSettled ? 'gate settled' : 'gate check pending'}`,
    window: w,
    closure: c,
  };
}

/**
 * The watchdog gate: every 6 hours while a crank window is open, once a day otherwise.
 * `utcHour` is the hour of the trigger; the daily run is the one in [00:00, 06:00).
 */
export function decideWatchdog({ sched, epoch, chain, utcHour, manual = false }) {
  if (manual) return { go: true, reason: 'manual run' };
  const w = crankWindowAt(sched, epoch);
  const open = w && (!chain || !windowClosed(chain, w.quarter).closed);
  if (open) return { go: true, reason: `Q${w.quarter} crank window is open; watching every 6 hours` };
  if (utcHour < 6) return { go: true, reason: 'daily check outside any window' };
  return { go: false, reason: 'outside any crank window; the daily check runs in the 00:00-06:00 slot' };
}

/**
 * The Claim gate. Weekly runs always go; the hourly trigger goes only inside a post-submit
 * window: from binding(Q) + 24h for 72 hours. Inside it, the Claim script itself waits for
 * 24 hours after the submitShares(Q) message actually landed, and sends at most once.
 */
export function decideClaim({ sched, epoch, trigger }) {
  if (trigger === 'manual') return { go: true, mode: 'manual', reason: 'manual run' };
  if (trigger === 'weekly') return { go: true, mode: 'weekly', reason: 'weekly Claim' };
  const g = sched.geometry;
  const delay = hours(sched, POST_SUBMIT_DELAY_HOURS);
  const span = hours(sched, POST_SUBMIT_WINDOW_HOURS);
  // Latest quarter whose post-submit window has opened.
  let q = Math.max(0, Math.floor((epoch - delay - g.activationEpoch - g.postPeriod - g.verificationWindow) / g.epochsPerQuarter));
  while (q >= 1 && binding(g, q) + delay > epoch) q -= 1;
  while (binding(g, q + 1) + delay <= epoch) q += 1;
  if (q >= 1 && epoch < binding(g, q) + delay + span) {
    return { go: true, mode: 'post-submit', quarter: q, reason: `post-submit Claim window for Q${q}` };
  }
  return { go: false, mode: null, reason: 'no post-submit Claim window open' };
}

/** Does the schedule file describe the same deployment as config/networks.json? */
export function scheduleMatchesConfig(sched, networkConfig) {
  const g = sched.geometry;
  const diffs = [];
  for (const k of ['activationEpoch', 'epochsPerQuarter', 'postPeriod', 'verificationWindow']) {
    if (Number(networkConfig[k]) !== Number(g[k])) diffs.push(`${k}: schedule ${g[k]}, config ${networkConfig[k]}`);
  }
  if (Number(networkConfig.epochSeconds) !== Number(sched.epochSeconds)) diffs.push('epochSeconds differs');
  if ((networkConfig.genesisUnix ?? null) !== (sched.genesisUnix ?? null)) diffs.push('genesisUnix differs');
  for (const k of ['sra', 'swa']) {
    if (String(networkConfig[k]).toLowerCase() !== String(sched.addresses?.[k]).toLowerCase()) diffs.push(`${k} address differs`);
  }
  return diffs;
}

const human = (iso) => {
  if (!iso) return null;
  const t = new Date(iso);
  const day = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'][t.getUTCDay()];
  const mon = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'][t.getUTCMonth()];
  const pad = (n) => String(n).padStart(2, '0');
  return `${day} ${pad(t.getUTCDate())} ${mon} ${t.getUTCFullYear()} ${pad(t.getUTCHours())}:${pad(t.getUTCMinutes())} UTC`;
};

/**
 * The schedule as the Markdown table docs/RUNBOOK.md carries. `npm run schedule` prints it,
 * and a unit test checks the runbook still contains exactly this, so the two cannot drift.
 */
export function scheduleMarkdown(file) {
  const asOf = `As of epoch ${file.generatedAtEpoch} (${human(file.generatedAt) ?? file.generatedAt}), from \`npm run schedule\` on ${file.network}.`;
  const rows = file.quarters.map((q) =>
    `| Q${q.quarter} | ${human(q.windowOpensUtc) ?? '—'} | ${human(q.bindingUtc) ?? '—'} (epoch ${q.bindingEpoch}) | ${human(q.everyRunUntilUtc) ?? '—'} | ${human(q.postSubmitClaimFromUtc) ?? '—'} | ${human(q.deadlineUtc) ?? '—'} (epoch ${q.deadlineEpoch}) |`
  );
  return [
    asOf,
    '',
    '| Quarter | Window opens | `submitShares(Q)` callable (binding) | Every run until | Post-submit Claim from | Deadline: Q lost after |',
    '| :-- | :-- | :-- | :-- | :-- | :-- |',
    ...rows,
  ].join('\n');
}
